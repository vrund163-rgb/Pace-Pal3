// Small 3x3 matrix helpers so the browser can draw the calibrated pitch back onto the video frame.
// The backend stores the homography that maps IMAGE pixels -> WORLD metres. To draw the pitch on
// the image we need the reverse (world -> image), which is the matrix inverse.

export type Mat3 = number[]; // flattened, row-major, 9 numbers

export function invert3x3(m: Mat3): Mat3 | null {
  const [a, b, c, d, e, f, g, h, i] = m;
  const A = e * i - f * h;
  const B = -(d * i - f * g);
  const C = d * h - e * g;
  const det = a * A + b * B + c * C;
  if (Math.abs(det) < 1e-12) return null;
  const inv = [
    A, -(b * i - c * h), b * f - c * e,
    B, a * i - c * g, -(a * f - c * d),
    C, -(a * h - b * g), a * e - b * d,
  ];
  return inv.map(v => v / det);
}

export function applyHomography(m: Mat3, x: number, y: number): [number, number] {
  const w = m[6] * x + m[7] * y + m[8];
  return [(m[0] * x + m[1] * y + m[2]) / w, (m[3] * x + m[4] * y + m[5]) / w];
}
